def get_project_mapping() -> dict[str, list[str]]:
    return PROJECT_BI_MAPPING


def resolve_project_from_bi_path(bi_path: str) -> str | None:
    """
    从 BI 组织路径解析出标准项目名。

    策略：
    1. 精确匹配
    2. 前缀匹配（BI 路径以映射路径开头）
    3. 反向前缀匹配（映射路径以 BI 路径开头）
    4. 兜底：从路径中提取关键词
    """
    if not bi_path:
        return None

    mapping = PROJECT_BI_MAPPING
    bi_path = bi_path.strip()

    for project, paths in mapping.items():
        if bi_path in paths:
            return project

    matched = []
    for project, paths in mapping.items():
        for p in paths:
            if bi_path.startswith(p + "/") or bi_path == p:
                matched.append((project, len(p)))
    if matched:
        matched.sort(key=lambda x: x[1], reverse=True)
        return matched[0][0]

    matched = []
    for project, paths in mapping.items():
        for p in paths:
            if p.startswith(bi_path + "/") or p == bi_path:
                matched.append((project, len(bi_path)))
    if matched:
        matched.sort(key=lambda x: x[1], reverse=True)
        return matched[0][0]

    path = bi_path
    path = re.sub(r"^金鹰/物业集团/外包/", "", path)
    path = re.sub(r"^金鹰/物业集团/南京金鹰国际物业集团有限公司[^/]*/", "", path)
    path = re.sub(r"^金鹰/金鹰商贸集团/连锁店/[^/]*/", "", path)
    parts = path.split("/")
    if parts:
        candidate = parts[0]
        for project in mapping:
            if candidate in project or project in candidate:
                return project
        return candidate

    return None


def get_bi_paths_for_project(project_name: str) -> list[str]:
    return PROJECT_BI_MAPPING.get(project_name, [])
